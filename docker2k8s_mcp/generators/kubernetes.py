"""Render a MigrationPlan into Kubernetes YAML.

Only the resources a plan actually needs are produced: a stateless API gets a
Deployment, a Service and a ConfigMap, while a database additionally gets a
StatefulSet with volumeClaimTemplates and a headless Service.
"""

from __future__ import annotations

import base64
import hashlib
import logging
from pathlib import Path
from typing import Any

import yaml

from ..config import get_settings
from ..schemas import (
    GeneratedManifest,
    GenerationResult,
    MigrationPlan,
    ProbePlan,
    ServicePlan,
    VolumePlan,
)
from ..security import REQUIRED_SECRET, resolve_project_path

logger = logging.getLogger(__name__)

MANAGED_BY = "docker2k8s-mcp"
HEADER = f"# Generated by {MANAGED_BY}. Review before applying.\n"
_PLACEHOLDER_B64 = base64.b64encode(REQUIRED_SECRET.encode()).decode()


def generate_manifests(
    plan: MigrationPlan,
    output_dir: str | Path | None = None,
    include_ingress: bool = False,
    ingress_host: str | None = None,
) -> GenerationResult:
    """Write one YAML file per Kubernetes resource and return an index of them.

    Files this tool generated earlier but that the plan no longer produces are
    renamed to ``*.stale`` so they cannot be applied by accident. Values a
    human already filled into a generated Secret are carried over.
    """
    settings = get_settings()
    target = _output_dir(plan, output_dir, settings.generated_dir)
    target.mkdir(parents=True, exist_ok=True)

    previous = {p.name for p in target.glob("*.yaml") if _is_managed(p)}
    manifests: list[GeneratedManifest] = []
    warnings: list[str] = []

    if plan.namespace != "default":
        manifests.append(_write(target, "namespace.yaml", _namespace(plan)))

    written_claims: set[str] = set()
    for service in plan.services:
        if service.config_map_name:
            manifests.append(
                _write(target, f"{service.name}-configmap.yaml", _config_map(plan, service))
            )
        if service.secret_name:
            filename = f"{service.name}-secret.yaml"
            secret, kept = _secret(plan, service, target / filename)
            manifests.append(_write(target, filename, secret))
            missing = sum(1 for v in secret["stringData"].values() if v == REQUIRED_SECRET)
            if kept:
                warnings.append(
                    f"Secret '{service.secret_name}': kept {kept} value(s) already filled in "
                    f"{filename}."
                )
            if missing > 0:
                warnings.append(
                    f"Secret '{service.secret_name}' contains {missing} {REQUIRED_SECRET} "
                    "placeholder(s); replace them, or create the Secret in the cluster, "
                    "before deploying."
                )

        # A StatefulSet carries its own storage via volumeClaimTemplates; a
        # Deployment needs standalone PVCs, which services may share.
        if service.workload_kind == "Deployment":
            for volume in service.volumes:
                claim = volume.claim_name
                if volume.source_kind != "named" or not claim or claim in written_claims:
                    continue
                written_claims.add(claim)
                manifests.append(_write(target, f"{claim}-pvc.yaml", _pvc(plan, service, volume)))

        filename = f"{service.name}-{service.workload_kind.lower()}.yaml"
        manifests.append(_write(target, filename, _workload(plan, service)))

        if service.create_service:
            manifests.append(_write(target, f"{service.name}-service.yaml", _service(plan, service)))

        if include_ingress and service.service_type in {"NodePort", "LoadBalancer"}:
            manifests.append(
                _write(target, f"{service.name}-ingress.yaml", _ingress(plan, service, ingress_host))
            )

    stale = sorted(previous - {Path(m.path).name for m in manifests})
    for name in stale:
        (target / name).replace(target / f"{name}.stale")
    if stale:
        warnings.append(
            f"Renamed {len(stale)} manifest(s) the plan no longer produces to *.stale so they "
            f"are not applied: {', '.join(stale)}."
        )

    logger.info("Generated %d Kubernetes resource(s) in %s", len(manifests), target)
    return GenerationResult(
        output_dir=str(target),
        project_name=plan.project_name,
        namespace=plan.namespace,
        manifests=manifests,
        warnings=warnings,
    )


def _output_dir(plan: MigrationPlan, output_dir: str | Path | None, generated_dir: Path) -> Path:
    """Default to generated/<project>/k8s; keep any override inside the sandbox.

    A relative override is taken relative to the generated directory, not the
    server's working directory, which MCP clients choose arbitrarily.
    """
    if not output_dir:
        return resolve_project_path(generated_dir / plan.project_name / "k8s", must_exist=False)
    return resolve_project_path(output_dir, must_exist=False, base=generated_dir)


def _is_managed(path: Path) -> bool:
    """True for files this tool wrote (it reads only the first line)."""
    try:
        with path.open(encoding="utf-8", errors="replace") as stream:
            return stream.readline() == HEADER
    except OSError:
        return False


