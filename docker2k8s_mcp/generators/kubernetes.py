def label_value(value: str) -> str:
    """Kubernetes label values are at most 63 characters.

    Longer values are shortened with a hash suffix so they stay unique and
    deterministic -- selectors depend on them and are immutable once applied.
    """
    if len(value) <= 63:
        return value
    digest = hashlib.sha256(value.encode()).hexdigest()[:8]
    return f"{value[:54].rstrip('-._')}-{digest}"


def _labels(plan: MigrationPlan, service: ServicePlan | None = None) -> dict[str, str]:
    labels = {
        "app.kubernetes.io/part-of": label_value(plan.project_name),
        "app.kubernetes.io/managed-by": MANAGED_BY,
    }
    if service is not None:
        labels.update(_selector(plan, service))
    return labels


def _selector(plan: MigrationPlan, service: ServicePlan) -> dict[str, str]:
    """The selector is a stable subset of the labels: it is immutable once applied."""
    return {
        "app.kubernetes.io/name": label_value(service.name),
        "app.kubernetes.io/instance": label_value(f"{plan.project_name}-{service.name}"),
    }


def _meta(plan: MigrationPlan, name: str, service: ServicePlan | None = None) -> dict[str, Any]:
    return {
        "name": name,
        "namespace": plan.namespace,
        "labels": _labels(plan, service),
    }


def _namespace(plan: MigrationPlan) -> dict[str, Any]:
    return {
        "apiVersion": "v1",
        "kind": "Namespace",
        "metadata": {"name": plan.namespace, "labels": _labels(plan)},
    }


def _config_map(plan: MigrationPlan, service: ServicePlan) -> dict[str, Any]:
    data = {e.key: str(e.value if e.value is not None else "") for e in service.env if not e.is_secret}
    return {
        "apiVersion": "v1",
        "kind": "ConfigMap",
        "metadata": _meta(plan, service.config_map_name or f"{service.name}-config", service),
        "data": data,
    }


def _secret(plan: MigrationPlan, service: ServicePlan, existing: Path) -> tuple[dict[str, Any], int]:
    """Build the Secret, reusing values a human already filled into ``existing``.

    Returns the document and how many keys carry a filled-in value. Values are
    only ever copied file to file; they are never returned to the caller.
    """
    keys = [e.key for e in service.env if e.is_secret]
    old_string, old_data = _filled_secret_values(existing)
    string_data: dict[str, str] = {}
    data: dict[str, str] = {}
    for key in keys:
        if key in old_string:
            string_data[key] = old_string[key]
        elif key in old_data:
            data[key] = old_data[key]
        else:
            # stringData keeps the file readable and avoids base64-encoding
            # placeholders that would otherwise look like real credentials.
            string_data[key] = REQUIRED_SECRET
    document: dict[str, Any] = {
        "apiVersion": "v1",
        "kind": "Secret",
        "metadata": _meta(plan, service.secret_name or f"{service.name}-secret", service),
        "type": "Opaque",
        "stringData": string_data,
    }
    if data:
        document["data"] = data
    kept = len(data) + sum(1 for v in string_data.values() if v != REQUIRED_SECRET)
    return document, kept


def _filled_secret_values(path: Path) -> tuple[dict[str, str], dict[str, str]]:
    """Non-placeholder stringData/data from a Secret file this tool generated."""
    if not path.is_file() or not _is_managed(path):
        return {}, {}
    try:
        with path.open(encoding="utf-8") as stream:
            doc = yaml.safe_load(stream)
    except (OSError, yaml.YAMLError):
        return {}, {}
    if not isinstance(doc, dict) or doc.get("kind") != "Secret":
        return {}, {}

    def filled(section: Any, placeholder: str) -> dict[str, str]:
        if not isinstance(section, dict):
            return {}
        return {
            str(k): str(v)
            for k, v in section.items()
            if v is not None and str(v).strip() not in {"", placeholder}
        }

    return filled(doc.get("stringData"), REQUIRED_SECRET), filled(doc.get("data"), _PLACEHOLDER_B64)


def _pvc(plan: MigrationPlan, service: ServicePlan, volume: VolumePlan) -> dict[str, Any]:
    spec: dict[str, Any] = {
        "accessModes": [volume.access_mode],
        "resources": {"requests": {"storage": volume.size}},
    }
    if volume.storage_class:
        spec["storageClassName"] = volume.storage_class
    # A shared claim belongs to the project, not to one service.
    owner = service if volume.claim_name == f"{service.name}-{volume.name}" else None
    return {
        "apiVersion": "v1",
        "kind": "PersistentVolumeClaim",
        "metadata": _meta(plan, volume.claim_name or f"{service.name}-{volume.name}", owner),
        "spec": spec,
    }


def _probe(probe: ProbePlan) -> dict[str, Any]:
    body: dict[str, Any] = {
        "initialDelaySeconds": probe.initial_delay_seconds,
        "periodSeconds": probe.period_seconds,
        "timeoutSeconds": probe.timeout_seconds,
        "failureThreshold": probe.failure_threshold,
    }
    if probe.kind == "httpGet":
        body["httpGet"] = {"path": probe.path or "/", "port": probe.port}
        if probe.scheme:
            body["httpGet"]["scheme"] = probe.scheme
    elif probe.kind == "tcpSocket":
        body["tcpSocket"] = {"port": probe.port}
    else:
        body["exec"] = {"command": probe.command or []}
    return body


def _security_context(service: ServicePlan) -> dict[str, Any]:
    context: dict[str, Any] = {}
    if service.privileged:
        context["privileged"] = True
    if service.run_as_user is not None:
        context["runAsUser"] = service.run_as_user
    if service.run_as_non_root:
        context["runAsNonRoot"] = True
    if service.allow_privilege_escalation is not None:
        context["allowPrivilegeEscalation"] = service.allow_privilege_escalation
    capabilities: dict[str, list[str]] = {}
    if service.capabilities_add:
        capabilities["add"] = service.capabilities_add
    if service.capabilities_drop:
        capabilities["drop"] = service.capabilities_drop
    if capabilities:
        context["capabilities"] = capabilities
    return context


def _container(plan: MigrationPlan, service: ServicePlan) -> dict[str, Any]:
    container: dict[str, Any] = {
        "name": service.name,
        "image": service.image,
        "imagePullPolicy": service.image_pull_policy,
    }
    if service.command:
        container["command"] = service.command
    if service.args:
        container["args"] = service.args
    if service.container_ports:
        container["ports"] = [
            {"name": p.name, "containerPort": p.container_port, "protocol": p.protocol}
            for p in service.container_ports
        ]

    env_from: list[dict[str, Any]] = []
    if service.config_map_name:
        env_from.append({"configMapRef": {"name": service.config_map_name}})
    if service.secret_name:
        env_from.append({"secretRef": {"name": service.secret_name}})
    if env_from:
        container["envFrom"] = env_from

    if service.volumes:
        container["volumeMounts"] = [
            {"name": v.name, "mountPath": v.mount_path, "readOnly": True}
            if v.read_only
            else {"name": v.name, "mountPath": v.mount_path}
            for v in service.volumes
        ]

    if service.readiness_probe:
        container["readinessProbe"] = _probe(service.readiness_probe)
    if service.liveness_probe:
        container["livenessProbe"] = _probe(service.liveness_probe)

    resources = _resources(service)
    if resources:
        container["resources"] = resources
    security_context = _security_context(service)
    if security_context:
        container["securityContext"] = security_context
    return container


def _resources(service: ServicePlan) -> dict[str, Any]:
    limits: dict[str, str] = {}
    requests: dict[str, str] = {}
    if service.resources:
        if service.resources.cpu_limit:
            limits["cpu"] = service.resources.cpu_limit
        if service.resources.memory_limit:
            limits["memory"] = service.resources.memory_limit
        if service.resources.cpu_request:
            requests["cpu"] = service.resources.cpu_request
        if service.resources.memory_request:
            requests["memory"] = service.resources.memory_request
    body: dict[str, Any] = {}
    if limits:
        body["limits"] = limits
    if requests:
        body["requests"] = requests
    return body


def _pod_volume(service: ServicePlan, volume: VolumePlan) -> dict[str, Any] | None:
    if volume.source_kind == "anonymous":
        return {"name": volume.name, "emptyDir": {}}
    if volume.source_kind == "tmpfs":
        empty_dir: dict[str, Any] = {"medium": "Memory"}
        if volume.size_limit:
            empty_dir["sizeLimit"] = volume.size_limit
        return {"name": volume.name, "emptyDir": empty_dir}
    if service.workload_kind == "Deployment":
        claim = volume.claim_name or f"{service.name}-{volume.name}"
        return {"name": volume.name, "persistentVolumeClaim": {"claimName": claim}}
    return None  # StatefulSet storage comes from volumeClaimTemplates


def _workload(plan: MigrationPlan, service: ServicePlan) -> dict[str, Any]:
    pod_spec: dict[str, Any] = {"containers": [_container(plan, service)]}

    pod_volumes = [v for v in (_pod_volume(service, vol) for vol in service.volumes) if v]
    if pod_volumes:
        pod_spec["volumes"] = pod_volumes

    template = {
        "metadata": {"labels": _labels(plan, service)},
        "spec": pod_spec,
    }

    spec: dict[str, Any] = {
        "replicas": service.replicas,
        "selector": {"matchLabels": _selector(plan, service)},
        "template": template,
    }

    if service.workload_kind == "StatefulSet":
        spec["serviceName"] = service.name
        claims = [
            {
                "metadata": {"name": volume.name},
                "spec": {
                    "accessModes": [volume.access_mode],
                    "resources": {"requests": {"storage": volume.size}},
                    **({"storageClassName": volume.storage_class} if volume.storage_class else {}),
                },
            }
            for volume in service.volumes
            if volume.source_kind == "named"
        ]
        if claims:
            spec["volumeClaimTemplates"] = claims
    else:
        # Recreate when a ReadWriteOnce claim is mounted: a rolling update
        # would start the new pod while the old one still holds the volume.
        spec["strategy"] = {"type": service.strategy}

    return {
        "apiVersion": "apps/v1",
        "kind": service.workload_kind,
        "metadata": _meta(plan, service.name, service),
        "spec": spec,
    }


def _service(plan: MigrationPlan, service: ServicePlan) -> dict[str, Any]:
    ports: list[dict[str, Any]] = []
    for port in service.service_ports:
        entry: dict[str, Any] = {
            "name": port.name,
            "port": port.port,
            "targetPort": port.target_port,
            "protocol": port.protocol,
        }
        if port.node_port and service.service_type == "NodePort":
            entry["nodePort"] = port.node_port
        ports.append(entry)

    spec: dict[str, Any] = {
        "selector": _selector(plan, service),
        "ports": ports,
        "type": service.service_type,
    }
    if service.headless:
        # Headless gives each StatefulSet pod a stable DNS name.
        spec["clusterIP"] = "None"
        spec["type"] = "ClusterIP"

    return {
        "apiVersion": "v1",
        "kind": "Service",
        "metadata": _meta(plan, service.name, service),
        "spec": spec,
    }


def _ingress(plan: MigrationPlan, service: ServicePlan, host: str | None) -> dict[str, Any]:
    port = service.service_ports[0].port if service.service_ports else 80
    rule: dict[str, Any] = {
        "http": {
            "paths": [
                {
                    "path": "/",
                    "pathType": "Prefix",
                    "backend": {"service": {"name": service.name, "port": {"number": port}}},
                }
            ]
        }
    }
    if host:
        rule["host"] = host
    return {
        "apiVersion": "networking.k8s.io/v1",
        "kind": "Ingress",
        "metadata": _meta(plan, service.name, service),
        "spec": {"rules": [rule]},
    }


